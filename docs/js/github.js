/* ==========================================================================
   github.js — reusable data access layer
   Reads static JSON generated by the Python downloader in ../output/data/
   ========================================================================== */

const GitHubData = (() => {
  const DATA_PATH = '../output/data/';
  const cache = {};

  async function fetchJSON(file) {
    if (cache[file]) return cache[file];
    const res = await fetch(DATA_PATH + file, { cache: 'no-store' });
    if (!res.ok) {
      throw new Error(`Failed to load ${file} (HTTP ${res.status})`);
    }
    const data = await res.json();
    cache[file] = data;
    return data;
  }

  const getStats = () => fetchJSON('stats.json');
  const getQuestions = () => fetchJSON('questions.json');
  const getSubmissions = () => fetchJSON('submissions.json');
  const getHeatmap = () => fetchJSON('heatmap.json');
  const getTags = () => fetchJSON('tags.json');
  const getLanguages = () => fetchJSON('languages.json');
  const getProfile = () => fetchJSON('profile.json');

  /** Builds a lookup of question title/difficulty by slug, used to enrich submissions. */
  async function getQuestionsBySlug() {
    const questions = await getQuestions();
    const map = {};
    questions.forEach(q => { map[q.title_slug] = q; });
    return map;
  }

  /** Computes current & longest daily-submission streaks from heatmap.json. */
  async function getStreaks() {
    const heatmap = await getHeatmap();
    const dateSet = new Set(heatmap.map(d => d.date));
    const sorted = [...dateSet].sort();
    if (sorted.length === 0) return { current: 0, longest: 0 };

    // Longest streak: scan consecutive-day runs across all recorded dates.
    let longest = 1;
    let run = 1;
    for (let i = 1; i < sorted.length; i++) {
      const prev = new Date(sorted[i - 1]);
      const cur = new Date(sorted[i]);
      const diffDays = Math.round((cur - prev) / 86400000);
      if (diffDays === 1) {
        run += 1;
      } else {
        longest = Math.max(longest, run);
        run = 1;
      }
    }
    longest = Math.max(longest, run);

    // Current streak: walk backwards from today (or yesterday) while days are present.
    let current = 0;
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const toKey = (d) => d.toISOString().slice(0, 10);

    let cursor = new Date(today);
    if (!dateSet.has(toKey(cursor))) {
      cursor.setDate(cursor.getDate() - 1); // allow "still active today" grace of one day
    }
    while (dateSet.has(toKey(cursor))) {
      current += 1;
      cursor.setDate(cursor.getDate() - 1);
    }

    return { current, longest };
  }

  function clearCache() {
    Object.keys(cache).forEach(k => delete cache[k]);
  }

  return {
    getStats, getQuestions, getSubmissions, getHeatmap,
    getTags, getLanguages, getProfile,
    getQuestionsBySlug, getStreaks, clearCache,
  };
})();
